#arithmetic operators
print "enter value of n1:\n";
my $n1=<STDIN>;
print "enter value of n2:\n";
my $n2=<STDIN>;


#addition
my $sum=$n1+$n2;
print "sum of n1 and n2 is $sum\n";

#subtraction
my $sub=$n1-$n2;
print "result of n1-n2 is $sub\n";

#multiplication
my $mul=$n1*$n2;
print "multiplication of n1 and n2 is $mul\n";

#division
my $div=$n1/$n2;
print "division of n1 by n2 is $div\n";

#modulus 
my $mod=$n1%$n2;
print "modulus of n1 by n2 is $mod\n";

#exponent
my $exp = $n1**$n2;
print "exponent of n1 is $exp\n";

